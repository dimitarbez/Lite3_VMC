    def test_quintic_interpolation_has_stationary_keyframe_boundaries(self):
        player = PatternPlayer(self.patterns)
        player.start("curiosity", 0.0)
        boundary = self.patterns["curiosity"].transition[0].duration
        epsilon = 1e-3
        before = player.command(boundary - epsilon)
        at = player.command(boundary)
        after = player.command(boundary + epsilon)
        for field in ("z", "roll", "pitch"):
            left_velocity = (getattr(at, field) - getattr(before, field)) / epsilon
            right_velocity = (getattr(after, field) - getattr(at, field)) / epsilon
            self.assertLess(abs(left_velocity), 0.001)
            self.assertLess(abs(right_velocity), 0.001)

    def test_idle_loop_seam_is_continuous_and_stationary(self):
        player = PatternPlayer(self.patterns)
        epsilon = 1e-3
        for emotion, profile in self.patterns.items():
            player.start(emotion, 0.0)
            transition = sum(item.duration for item in profile.transition) * profile.duration / profile.speed
            idle = sum(item.duration for item in profile.idle) / profile.speed
            seam = transition + idle
            before = player.command(seam - epsilon)
            at = player.command(seam)
            after = player.command(seam + epsilon)
            for field in ("x", "y", "yaw", "z", "roll", "pitch"):
                self.assertLess(abs(getattr(at, field) - getattr(before, field)), 1e-5)
                self.assertLess(abs(getattr(after, field) - getattr(at, field)), 1e-5)

    def test_idle_can_be_softer_and_slower_without_weakening_entrance(self):
        normal = PatternPlayer(self.patterns)
        softened = PatternPlayer(
            self.patterns, idle_amplitude_scale=0.65, idle_time_scale=1.25
        )
        profile = self.patterns["curiosity"]
        transition = sum(item.duration for item in profile.transition)
        normal.start("curiosity", 0.0)
        softened.start("curiosity", 0.0)

        # Entrance choreography is unchanged.
        self.assertEqual(normal.command(transition * 0.5), softened.command(transition * 0.5))

        # At the first softened-loop endpoint, amplitude is 65% of the authored
        # keyframe and the loop takes 25% longer.
        first_idle_end = transition + profile.idle[0].duration * 1.25
        soft_pose = softened.command(first_idle_end)
        expected = profile.idle[0].twist
        self.assertAlmostEqual(soft_pose.z, expected.z * 0.65)
        self.assertAlmostEqual(soft_pose.roll, expected.roll * 0.65)
        normal_idle = sum(item.duration for item in profile.idle)
        soft_idle = normal_idle * 1.25
        self.assertGreater(soft_idle, normal_idle)

