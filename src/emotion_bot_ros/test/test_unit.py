    def test_emotion_change_cancels_then_reaches_neutral_before_new_action(self):
        controller = FluidExpressionController(
            self.patterns,
            neutral_return_time=0.35,
            neutral_hold_time=0.25,
            min_dwell=0.0,
        )
        controller.update("joy", 0.8, 0.9, 0.0)
        controller.command(0.0)
        controller.command(0.70)
        controller.consume_action(0.70)  # initial generation cancel
        self.assertFalse(controller.output.is_zero())

        controller.update("anger", -0.8, 1.0, 0.71)
        cancel = controller.consume_action(0.71)
        self.assertEqual(cancel["kind"], "cancel")
        self.assertIsNone(controller.consume_action(0.90))
        for moment in (0.81, 0.91, 1.01, 1.06):
            controller.command(moment)
        self.assertEqual(controller.output, TwistValue())
        self.assertEqual(controller.selected_emotion, "joy")
        self.assertEqual(controller.transition_emotion, "anger")

        # Exact neutral is held as a fresh canonical stance before the new
        # entrance begins; no prior pose residue can feed its first keyframe.
        self.assertEqual(controller.command(1.20), TwistValue())
        controller.command(1.32)
        self.assertEqual(controller.selected_emotion, "anger")
        self.assertEqual(controller.player.started_at, 1.32)

        # Starting the target is a separate generation after the reset, so a
        # stale action from joy cannot overtake anger's entrance stomp.
        target_cancel = controller.consume_action(1.32)
        stomp = controller.consume_action(1.33)
        self.assertEqual(target_cancel["kind"], "cancel")
        self.assertEqual(stomp["kind"], "start")
        self.assertEqual(stomp["emotion"], "anger")
        self.assertEqual(stomp["action"], "stomp")
        self.assertGreater(stomp["generation"], cancel["generation"])

