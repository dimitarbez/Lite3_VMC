    def test_dynamic_actions_are_one_shot_and_never_enable_locomotion(self):
        controller = SafetyController(Limits())
        controller.request_stance_preparation(0.0)
        controller.step(0.0)
        controller.set_enabled(True, 0.1)
        controller.update_expression(TwistValue(z=0.02), 0.1)
        controller.update_expression_action("hop", 0.1)
        hop = controller.step(0.11)
        self.assertEqual(hop.joy.buttons[4], 1)
        self.assertEqual(hop.joy.buttons[5], 0)
        self.assertEqual(hop.joy.axes[4], 0.0)
        self.assertEqual(hop.joy.axes[3], 0.0)
        self.assertEqual(hop.joy.axes[0], 0.0)
        self.assertEqual(controller.step(0.12).joy.buttons[4], 0)

        controller.update_expression_action("stomp", 0.2)
        stomp = controller.step(0.21)
        self.assertEqual(stomp.joy.buttons[4], 0)
        self.assertEqual(stomp.joy.buttons[5], 1)

        # A String action may arrive one ROS tick before its cross-faded Twist.
        # It remains eligible only while the same fresh watchdog is active.
        early = SafetyController(Limits())
        early.request_stance_preparation(0.0)
        early.step(0.0)
        early.set_enabled(True, 0.1)
        early.update_expression(TwistValue(), 0.1)
        early.update_expression_action("hop", 0.1)
        self.assertEqual(early.step(0.11).joy.buttons[4], 1)

        blocked = SafetyController(Limits(), allow_dynamic_actions=False)
        blocked.request_stance_preparation(0.0)
        blocked.step(0.0)
        blocked.set_enabled(True, 0.1)
        blocked.update_expression(TwistValue(z=0.02), 0.1)
        blocked.update_expression_action("hop", 0.1)
        self.assertEqual(blocked.step(0.11).joy.buttons[4], 0)

        # A hop/stomp interrupts a locomotion command and is emitted only
        # after the bridge has returned to the torque stance.
        interrupt = SafetyController(Limits(), allow_locomotion=True, expression_timeout=1.0)
        interrupt.set_enabled(True, 0.0)
        interrupt.update_expression(TwistValue(x=0.04), 0.0)
        self.assertEqual(interrupt.step(0.01).joy.buttons[1], 1)
        self.assertEqual(interrupt.step(0.40).joy.buttons[7], 1)
        interrupt.update_expression_action("stomp", 0.41)
        ramp = interrupt.step(0.42)
        self.assertEqual(ramp.action, "gait_to_stance_zero_hold")
        self.assertEqual(ramp.joy.buttons[1], 0)
        stance = interrupt.step(0.68)
        self.assertEqual(stance.action, "gait_to_stance_minimum_hold")
        stance = interrupt.step(1.01)
        self.assertEqual(stance.joy.buttons[1], 1)
        settling = interrupt.step(1.20)
        self.assertEqual(settling.action, "gait_to_stance_settling")
        stomp = interrupt.step(1.37)
        self.assertEqual(stomp.joy.buttons[5], 1)
        self.assertEqual(stomp.joy.axes, [0.0] * 8)

    def test_generation_order_and_cancel_before_start(self):
        controller = SafetyController(Limits())
        controller.request_stance_preparation(0.0)
        controller.step(0.0)
        controller.set_enabled(True, 0.1)
        controller.update_expression(TwistValue(z=0.01), 0.1)
        controller.update_expression_action(
            "none", 0.1, kind="cancel", generation=7, occurrence="change"
        )
        controller.update_expression_action(
            "stomp", 0.1, kind="start", generation=7, occurrence="entrance:0"
        )
        cancel = controller.step(0.11)
        start = controller.step(0.12)
        self.assertEqual(cancel.joy.buttons[6], 1)
        self.assertEqual(cancel.joy.buttons[5], 0)
        self.assertEqual(start.joy.buttons[6], 0)
        self.assertEqual(start.joy.buttons[5], 1)

        # Older generations and duplicate occurrence IDs cannot replay.
        controller.update_expression_action(
            "hop", 0.13, kind="start", generation=6, occurrence="old"
        )
        controller.update_expression_action(
            "stomp", 0.14, kind="start", generation=7, occurrence="entrance:0"
        )
        self.assertEqual(controller.step(0.15).joy.buttons[4], 0)
        self.assertEqual(controller.step(0.15).joy.buttons[5], 0)

